"""
知识点提取模块 Prompt 模板。
"""

POINT_EXTRACT_PROMPT = """你是知识库的知识点提取器。从下面的文本片段中提取知识点。

规则：
1. 识别文本中"重点阐述"的主题（topic），即这段文字围绕什么概念/技术/方法/实体展开
2. 只提取被重点说明的主题，通常每个片段 1~5 个；仅在句中一笔带过的概念不要单独提取
3. 语义相近或上下位的概念合并为一个 topic（如"pip"和"包管理"若讲的是同一件事，只取其一）
4. 每个提取结果给出该片段中与 topic 直接相关的内容摘录，保留关键细节，逐字摘抄不要改写
5. 忽略纯过渡句、页眉页脚、目录、与知识无关的内容
6. topic 用简洁的标准术语命名（如"自注意力机制"、"梯度下降"），不要整句
7. 只输出 JSON 数组，不要任何其他文字，没有可提取内容时输出 []：
[{{"topic": "关键主语", "description": "相关内容摘录"}}]

文本片段：
{chunk_text}"""

POINT_REWRITE_PROMPT = """你是知识库的知识点整理器。将新增内容融合进知识点已有内容，生成一段完整的知识点描述。

规则：
1. 保留已有内容和新内容中的全部关键信息，去除重复
2. 输出一段连贯、结构清晰的知识点描述，语言与原文一致
3. 不添加原文没有的信息
4. 只输出 JSON，不要任何其他文字：
{{"content": "融合后的知识点内容"}}

知识点主题：{topic}

已有内容：
{old_content}

新增内容：
{delta}"""
